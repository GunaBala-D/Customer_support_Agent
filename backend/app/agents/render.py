"""Deterministic response templates for tool results.

Tool answers are rendered from the tool's JSON, not generated by the LLM. Order facts (dates,
tracking numbers, totals) therefore cannot be paraphrased wrongly by a small local model.
The LLM is reserved for what needs language understanding: classification fallback and
grounded knowledge answers.
"""
from datetime import datetime


def _date(iso: str | None) -> str:
    return datetime.fromisoformat(iso).strftime("%b %d, %Y") if iso else "n/a"


def money(amount: float, currency: str = "USD") -> str:
    return f"{amount:,.2f} {currency}"


def render_order_status(status: dict, items: dict | None) -> str:
    oid, st = status["order_id"], status["status"]
    headline = {
        "pending": f"Order {oid} has been received and is waiting to be processed.",
        "processing": f"Order {oid} is being prepared in our warehouse and has not shipped yet.",
        "shipped": f"Order {oid} has shipped on {_date(status['shipped_at'])}.",
        "delivered": f"Order {oid} was delivered on {_date(status['delivered_at'])}.",
        "cancelled": f"Order {oid} was cancelled.",
        "refunded": f"Order {oid} was refunded.",
    }.get(st, f"Order {oid} is currently '{st}'.")
    lines = [headline]
    if st == "shipped" and status.get("carrier"):
        lines.append(f"Carrier: {status['carrier']}, tracking number {status['tracking_number']}.")
    if items and items.get("items"):
        lines.append("Items: " + ", ".join(f"{i['quantity']} x {i['name']}" for i in items["items"]) + ".")
    lines.append(f"Total: {money(status['total'], status['currency'])} (payment: {status['payment_status'].replace('_', ' ')}).")
    return "\n".join(lines)


def render_refund_eligibility(r: dict) -> str:
    oid, window = r["order_id"], r["window_days"]
    reason = r["reason"]
    if r["eligible"]:
        return (
            f"Order {oid} was delivered {r['days_since_delivery']} days ago, so it is within the "
            f"{window}-day return window (until {_date(r['deadline'])})."
        )
    return {
        "window_expired": f"Order {oid} was delivered {r.get('days_since_delivery')} days ago, which is past the "
                          f"{window}-day return window (it ended {_date(r.get('deadline'))}).",
        "not_delivered": f"Order {oid} is {r['status']} and has not been delivered yet, so a return can't be started. "
                         "Returns are possible after delivery.",
        "cancelled": f"Order {oid} was cancelled, so there is nothing to return.",
        "already_refunded": f"Order {oid} has already been refunded.",
    }.get(reason, f"Order {oid} is not eligible for a refund.")


def render_customer(c: dict) -> str:
    lines = [
        f"Here are the details on your account, {c['name']}:",
        f"Customer ID: {c['customer_id']}",
        f"Email: {c['email']}",
    ]
    if c.get("phone_masked"):
        lines.append(f"Phone: {c['phone_masked']}")
    lines += [f"Membership tier: {c['tier']}", f"Member since: {_date(c['member_since'])}", f"Orders on file: {c['order_count']}"]
    return "\n".join(lines)


